/************************************************************************/
/*                        Internal Definitions                          */
/************************************************************************/

/* VGA CRT Controller ports (same as text-mode) */
#define VGA_CRT_ADDR    0x3D4
#define VGA_CRT_DATA    0x3D5

/* VGA Sequencer ports */
#define VGA_SEQ_ADDR    0x3C4
#define VGA_SEQ_DATA    0x3C5

/* VGA Graphics Controller ports */
#define VGA_GC_ADDR     0x3CE
#define VGA_GC_DATA     0x3CF

/* VGA Attribute Controller ports */
#define VGA_AC_ADDR     0x3C0
#define VGA_AC_DATA     0x3C0
#define VGA_AC_READ     0x3C1

/* VGA DAC (palette) ports */
#define VGA_DAC_MASK    0x3C6
#define VGA_DAC_READ    0x3C7
#define VGA_DAC_WRITE   0x3C8
#define VGA_DAC_DATA    0x3C9

/* Miscellaneous Output Register */
#define VGA_MISC_READ   0x3CC
#define VGA_MISC_WRITE  0x3C2

struct graphics_device {
    struct platform_bus_ops* bus_ops;
    uspinlock lock;    /* user-mode spinlock (gfx_* run at ring-3) */
    u8* fb;            /* framebuffer pointer (0xA0000) */
    size_t    curr_col;     /* cursor column (0..GFX_COLS-1) */
    size_t    curr_row;     /* cursor row    (0..GFX_ROWS-1) */
    u8   curr_fg;      /* current foreground color */
    u8   curr_bg;      /* current background color */
};

static struct graphics_device gfx_dev = {
    .lock     = USPINLOCK_INIT,
    .fb       = (u8*)GFX_BUF_ADDR,
    .curr_col = 0,
    .curr_row = 0,
    .curr_fg  = GFX_LIGHT_GREY,
    .curr_bg  = GFX_BLACK,
};

/* ---- RING3-safe VGA I/O -----------------------------------------------
 * The platform bus ops are never attached to a DRIVER_CLASS_USER device
 * (probe() is not called for user drivers), so the graphics server uses
 * its own wrappers around the io layer.  iowrite8()/ioread8() execute the
 * instruction directly at CPL0 and go through the capability-checked
 * syscall gate at CPL3 (see kernel/io.c). */
static int gfx_out8(u16 port, u8 data)
{
    iowrite8(port, data);
    return 0;
}

static int gfx_in8(u16 port)
{
    return (int)ioread8(port);
}

static struct platform_bus_ops gfx_bus_ops = {
    .in_port8  = gfx_in8,
    .out_port8 = gfx_out8,
};

